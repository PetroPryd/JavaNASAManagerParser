    private void loadItems() {
        try {
            itemsModel.clear();
            for (NasaItem item : repository.selectNasaItems()) {
                itemsModel.addElement(item);
            }
            linkedModel.clear();
            availableModel.clear();
            selectedItem = null;
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not load items: " + ex.getMessage());
        }
    }

    private void onItemSelected() {
        selectedItem = lstItems.getSelectedValue();
        refreshMissionLists();
    }

    private void refreshMissionLists() {
        linkedModel.clear();
        availableModel.clear();
        if (selectedItem == null) {
            return;
        }
        try {
            List<Mission> linked = repository.selectMissionsForNasaItem(selectedItem.getId());
            for (Mission m : linked) {
                linkedModel.addElement(m);
            }
            Set<Integer> linkedIds = linked.stream()
                    .map(Mission::getId)
                    .collect(Collectors.toSet());
            for (Mission m : repository.selectMissions()) {
                boolean isLinked = linkedIds.contains(m.getId());
                if (rbAll.isSelected() || !isLinked) {
                    availableModel.addElement(m);
                }
            }
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not load missions: " + ex.getMessage());
        }
    }

    @Override
    public void addMission(Mission mission) {
        if (selectedItem == null) {
            MessageUtils.showInformationMessage("Link", "Select a NASA item first.");
            return;
        }
        for (int i = 0; i < linkedModel.size(); i++) {
            if (linkedModel.get(i).getId() == mission.getId()) {
                return;
            }
        }
        try {
            repository.linkNasaItemMission(selectedItem.getId(), mission.getId());
            refreshMissionLists();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not link: " + ex.getMessage());
        }
    }

    public void removeMission(Mission mission) {
        if (selectedItem == null) {
            MessageUtils.showInformationMessage("Unlink", "Select a NASA item first.");
            return;
        }
        try {
            repository.unlinkNasaItemMission(selectedItem.getId(), mission.getId());
            refreshMissionLists();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not unlink: " + ex.getMessage());
        }
    }
