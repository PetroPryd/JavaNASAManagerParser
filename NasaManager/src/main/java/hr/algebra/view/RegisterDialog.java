    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());
        String confirm = new String(txtConfirm.getPassword());

        if (!password.equals(confirm)) {
            MessageUtils.showErrorMessage("Registration", "Passwords do not match.");
            return;
        }
        try {
            authService.register(username, password);
            MessageUtils.showInformationMessage("Registration", "Account created. You can now log in.");
            dispose();
        } catch (IllegalArgumentException ex) {
            MessageUtils.showErrorMessage("Registration", ex.getMessage());
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not register: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

