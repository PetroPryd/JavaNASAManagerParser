    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!validateForm()) {
            return;
        }
        try {
            Mission mission = new Mission(
                    txtName.getText().trim(),
                    txtCode.getText().trim(),
                    (Agency) cboAgency.getSelectedItem(),
                    (Integer) spnLaunchYear.getValue());
            repository.createMission(mission);
            MessageUtils.showInformationMessage("Added", "Mission added.");
            loadMissions();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not add: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedMission == null) {
            MessageUtils.showInformationMessage("Update", "Select a mission first.");
            return;
        }
        if (!validateForm()) {
            return;
        }
        try {
            Mission mission = new Mission(
                    selectedMission.getId(),
                    txtName.getText().trim(),
                    txtCode.getText().trim(),
                    (Agency) cboAgency.getSelectedItem(),
                    (Integer) spnLaunchYear.getValue());
            repository.updateMission(selectedMission.getId(), mission);
            MessageUtils.showInformationMessage("Updated", "Mission updated.");
            loadMissions();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not update: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedMission == null) {
            MessageUtils.showInformationMessage("Delete", "Select a mission first.");
            return;
        }
        if (!MessageUtils.showConfirmDialog("Delete", "Delete mission \"" + selectedMission.getName() + "\"?")) {
            return;
        }
        try {
            repository.deleteMission(selectedMission.getId());
            MessageUtils.showInformationMessage("Deleted", "Mission deleted.");
            loadMissions();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not delete: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

