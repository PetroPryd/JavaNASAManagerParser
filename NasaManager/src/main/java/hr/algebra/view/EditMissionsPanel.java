    private void loadMissions() {
        try {
            tableModel.setItems(repository.selectMissions());
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not load missions: " + ex.getMessage());
        }
    }

    private void showSelectedMission() {
        int viewRow = tblMissions.getSelectedRow();
        if (viewRow < 0) {
            return;
        }
        int modelRow = tblMissions.convertRowIndexToModel(viewRow);
        selectedMission = tableModel.getItemAt(modelRow);
        fillForm(selectedMission);
    }

    private void fillForm(Mission m) {
        txtName.setText(m.getName());
        txtCode.setText(m.getCode());
        cboAgency.setSelectedItem(m.getAgency() == null ? Agency.OTHER : m.getAgency());
        spnLaunchYear.setValue(m.getLaunchYear() == null ? Year.now().getValue() : m.getLaunchYear());
    }

    private void clearForm() {
        selectedMission = null;
        txtName.setText("");
        txtCode.setText("");
        cboAgency.setSelectedIndex(0);
        spnLaunchYear.setValue(Year.now().getValue());
        tblMissions.clearSelection();
    }

    private boolean validateForm() {
        if (txtName.getText().trim().isEmpty()) {
            MessageUtils.showErrorMessage("Validation", "Name is required.");
            return false;
        }
        return true;
    }
