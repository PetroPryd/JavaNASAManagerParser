    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());
        try {
            Optional<User> user = authService.authenticate(username, password);
            if (user.isPresent()) {
                Session.getInstance().setCurrentUser(user.get());
                new NasaManager().setVisible(true);
                dispose();
            } else {
                MessageUtils.showErrorMessage("Login failed", "Invalid username or password.");
            }
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not connect: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnLoginActionPerformed

