    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
        setBusy(true, "Loading from the NASA feed...");
        new SwingWorker<Integer, Void>() {
            @Override
            protected Integer doInBackground() throws Exception {
                List<NasaItem> items = NasaItemParser.parse();
                repository.createNasaItems(items);
                return items.size();
            }

            @Override
            protected void done() {
                try {
                    int count = get();
                    setBusy(false, "Loaded " + count + " items.");
                    MessageUtils.showInformationMessage("Load complete", count + " items loaded from the feed.");
                } catch (Exception ex) {
                    setBusy(false, "Load failed.");
                    MessageUtils.showErrorMessage("Error", "Could not load: " + ex.getMessage());
                }
            }
        }.execute();
    }//GEN-LAST:event_btnLoadActionPerformed

    private void btnDeleteAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteAllActionPerformed
        if (!MessageUtils.showConfirmDialog("Delete all data",
                "Delete ALL NASA items and their downloaded images?")) {
            return;
        }
        setBusy(true, "Deleting all data...");
        new SwingWorker<Void, Void>() {
            @Override
            protected Void doInBackground() throws Exception {
                for (NasaItem item : repository.selectNasaItems()) {
                    deleteImage(item.getPicturePath());
                }
                repository.deleteAllNasaItems();
                return null;
            }

            @Override
            protected void done() {
                try {
                    get();
                    setBusy(false, "All data deleted.");
                    MessageUtils.showInformationMessage("Done", "All NASA items and their images were deleted.");
                } catch (Exception ex) {
                    setBusy(false, "Delete failed.");
                    MessageUtils.showErrorMessage("Error", "Could not delete: " + ex.getMessage());
                }
            }
        }.execute();
    }//GEN-LAST:event_btnDeleteAllActionPerformed

    private void setBusy(boolean busy, String status) {
        btnLoad.setEnabled(!busy);
        btnDeleteAll.setEnabled(!busy);
        progressBar.setVisible(busy);
        progressBar.setIndeterminate(busy);
        lblStatus.setText(status);
    }

    private void deleteImage(String picturePath) {
        if (picturePath == null || picturePath.isBlank()) {
            return;
        }
        try {
            Files.deleteIfExists(Paths.get(picturePath));
        } catch (Exception ex) {
            // ignore a single image failure
        }
    }

