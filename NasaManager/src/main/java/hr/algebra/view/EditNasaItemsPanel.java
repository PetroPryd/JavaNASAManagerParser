    private void loadItems() {
        try {
            tableModel.setItems(repository.selectNasaItems());
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not load items: " + ex.getMessage());
        }
    }

    private void showSelectedItem() {
        int viewRow = tblItems.getSelectedRow();
        if (viewRow < 0) {
            return;
        }
        int modelRow = tblItems.convertRowIndexToModel(viewRow); // map sorted view -> model
        selectedItem = tableModel.getItemAt(modelRow);
        fillForm(selectedItem);
    }

    private void fillForm(NasaItem item) {
        pendingImageSource = null;

        txtTitle.setText(item.getTitle());
        txtLink.setText(item.getLink());
        txtDescription.setText(item.getDescription());
        txtPublished.setText(item.getPublishedDate() == null ? ""
                : item.getPublishedDate().format(NasaItem.DATE_FORMATTER));
        pendingPicturePath = item.getPicturePath();
        showImage(item.getPicturePath());
    }

    private void clearForm() {
        pendingImageSource = null;

        selectedItem = null;
        pendingPicturePath = null;
        txtTitle.setText("");
        txtLink.setText("");
        txtDescription.setText("");
        txtPublished.setText("");
        lblImage.setIcon(null);
        lblImage.setText("(no image)");
        tblItems.clearSelection();
    }

    private void showImage(String picturePath) {
        previewImage(picturePath == null ? null : new File(picturePath));
    }

    private void previewImage(File file) {
        try {
            if (file != null && file.exists()) {
                lblImage.setText("");
                lblImage.setIcon(IconUtils.createIcon(file, IMG_W, IMG_H));
            } else {
                lblImage.setIcon(null);
                lblImage.setText("(no image)");
            }
        } catch (IOException ex) {
            lblImage.setIcon(null);
            lblImage.setText("(image error)");
        }
    }

    private boolean validateForm() {
        if (txtTitle.getText().trim().isEmpty()) {
            MessageUtils.showErrorMessage("Validation", "Title is required.");
            return false;
        }
        if (txtLink.getText().trim().isEmpty()) {
            MessageUtils.showErrorMessage("Validation", "Link is required.");
            return false;
        }
        return true;
    }

    private String persistImageIfChosen(String existingPath) throws IOException {
        if (pendingImageSource == null) {
            return existingPath;
        }
        String name = pendingImageSource.getName();
        String ext = name.contains(".") ? name.substring(name.lastIndexOf(".")) : ".jpg";
        String target = "assets" + File.separator + UUID.randomUUID() + ext;
        FileUtils.copy(pendingImageSource.getAbsolutePath(), target);
        return target;
    }

    private void deleteImageFile(String picturePath) {
        if (picturePath == null || picturePath.isBlank()) {
            return;
        }
        try {
            Files.deleteIfExists(java.nio.file.Paths.get(picturePath));
        } catch (Exception ex) {
            // just ignores 
        }
    }

    private void applyFilter() {
        String text = txtFilter.getText().trim();
        if (text.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + Pattern.quote(text)));
        }
    }
