    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!validateForm()) {
            return;
        }
        try {
            String picturePath = persistImageIfChosen(null);
            NasaItem item = new NasaItem(
                    txtTitle.getText().trim(),
                    txtLink.getText().trim(),
                    txtDescription.getText().trim(),
                    picturePath,
                    LocalDateTime.now());
            repository.createNasaItem(item);
            MessageUtils.showInformationMessage("Added", "Item added.");
            loadItems();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not add: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedItem == null) {
            MessageUtils.showInformationMessage("Update", "Select an item in the table first.");
            return;
        }
        if (!validateForm()) {
            return;
        }
        try {
            String oldPath = selectedItem.getPicturePath();
            String picturePath = persistImageIfChosen(oldPath);
            NasaItem item = new NasaItem(
                    selectedItem.getId(),
                    txtTitle.getText().trim(),
                    txtLink.getText().trim(),
                    txtDescription.getText().trim(),
                    picturePath,
                    selectedItem.getPublishedDate());
            repository.updateNasaItem(selectedItem.getId(), item);
            if (pendingImageSource != null && oldPath != null && !oldPath.equals(picturePath)) {
                deleteImageFile(oldPath);
            }
            MessageUtils.showInformationMessage("Updated", "Item updated.");
            loadItems();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not update: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedItem == null) {
            MessageUtils.showInformationMessage("Delete", "Select an item in the table first.");
            return;
        }
        if (!MessageUtils.showConfirmDialog("Delete", "Delete \"" + selectedItem.getTitle() + "\"?")) {
            return;
        }
        try {
            String path = selectedItem.getPicturePath();
            repository.deleteNasaItem(selectedItem.getId());
            deleteImageFile(path);
            MessageUtils.showInformationMessage("Deleted", "Item deleted.");
            loadItems();
            clearForm();
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Error", "Could not delete: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed


